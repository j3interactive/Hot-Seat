#!/usr/bin/env python3
"""Generate db/seed.sql from data/floor-layout.json.

Run from the repo root:  python3 tools/build_seed.py
Validates the layout (unique seat IDs, desks belong to their pod) and prints a summary.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LAYOUT = ROOT / "data" / "floor-layout.json"
OUT = ROOT / "db" / "seed.sql"


def q(value):
    if value is None:
        return "NULL"
    return "N'" + str(value).replace("'", "''") + "'"


def cells_of(pod):
    if "cells" in pod:
        return [(sid, c, r) for sid, c, r in pod["cells"]]
    out = []
    for r, row in enumerate(pod["rows"]):
        for c, sid in enumerate(row):
            if sid:
                out.append((sid, c, r))
    return out


def main():
    layout = json.loads(LAYOUT.read_text(encoding="utf-8"))
    grids = layout["grids"]
    notes = layout.get("seatNotes", {})
    lines = [
        "-- GENERATED by tools/build_seed.py from data/floor-layout.json. Do not edit by hand.",
        "SET NOCOUNT ON;",
        "BEGIN TRANSACTION;",
        "DELETE FROM dbo.SeatDay; DELETE FROM dbo.Block; DELETE FROM dbo.Seat; DELETE FROM dbo.Pod; DELETE FROM dbo.Area;",
    ]
    seen = {}
    errors = []
    summary = []

    for area in layout["areas"]:
        g = grids[area["grid"]]
        lines.append(
            "INSERT INTO dbo.Area (AreaId, Name, MapWidth, MapHeight, GridSx, GridSy, SeatW, SeatH, Note, LandmarksJson) VALUES "
            f"({q(area['id'])}, {q(area['name'])}, {area['width']}, {area['height']}, {g['sx']}, {g['sy']}, {g['w']}, {g['h']}, "
            f"{q(area.get('note'))}, {q(json.dumps(area.get('landmarks', []), ensure_ascii=False))});"
        )
        area_count = 0
        for pod in area["pods"]:
            lines.append(
                "INSERT INTO dbo.Pod (PodId, AreaId, Label, SupervisorLabel, X, Y) VALUES "
                f"({q(pod['id'])}, {q(area['id'])}, {q(pod['label'])}, {q(pod.get('supervisor'))}, {pod['x']}, {pod['y']});"
            )
            cells = cells_of(pod)
            ids = {sid for sid, _, _ in cells}
            for d in pod.get("desks", []) + pod.get("trainerDesks", []):
                if d not in ids:
                    errors.append(f"desk {d} is not in pod {pod['id']}")
            for sid, c, r in cells:
                if sid in seen:
                    errors.append(f"duplicate seat {sid} in {pod['id']} and {seen[sid]}")
                seen[sid] = pod["id"]
                if sid in pod.get("desks", []):
                    seat_type = "SupervisorDesk"
                elif sid in pod.get("trainerDesks", []):
                    seat_type = "TrainerDesk"
                else:
                    seat_type = pod.get("seatType", "Agent")
                lines.append(
                    "INSERT INTO dbo.Seat (SeatId, PodId, GridCol, GridRow, SeatType, Note) VALUES "
                    f"({q(sid)}, {q(pod['id'])}, {c}, {r}, {q(seat_type)}, {q(notes.get(sid))});"
                )
                area_count += 1
        summary.append(f"{area['name']}: {area_count} seats")

    for sid in notes:
        if sid not in seen:
            errors.append(f"note for unknown seat {sid}")

    if errors:
        print("Layout errors:\n  " + "\n  ".join(errors), file=sys.stderr)
        sys.exit(1)

    lines.append("COMMIT TRANSACTION;")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(summary))
    print(f"Total: {len(seen)} seats -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
